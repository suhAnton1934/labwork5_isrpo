def area(a, h):
	'''
		Принимает числа 'a' - сторона треугольника
		'h' - высота треугольника, опущенная на сторону a, 
		Возвращает площадь треугольника S = (a * h) / 2 
	'''
	return (a * h) / 2

def perimeter(a, b, c):
	'''Принимает числа 'a', 'b', 'c' - стороны треугольника, возвращает периметр P = (a + b + c)'''
	return a + b + c
